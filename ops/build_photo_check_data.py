#!/usr/bin/env python3
"""Build site/assets/js/photo-check-zones.js: the 114 zone ids the Photos API
exposes at GET /v1/zones, with the room and display name that API does not
return, for the (not yet linked) photo-check.html page's zone picker.

Reads the same source photos/methodology.py reads (content.json and
ops/zone-name-map.json) through that module directly, rather than
re-deriving the slug rule here, so the two can never disagree: the slug this
page sends as the `zone` query parameter is guaranteed to be one GET /v1/zones
would also return.
"""
from __future__ import annotations

import importlib.util
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "site", "assets", "js", "photo-check-zones.js")


def _load_methodology():
    spec = importlib.util.spec_from_file_location(
        "sixs_photos_methodology", os.path.join(ROOT, "photos", "methodology.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def zone_rows():
    m = _load_methodology()
    rows = []
    for slug in m.zone_slugs():
        room, name, _z = m.ZONES[slug]
        rows.append({"slug": slug, "room": room, "name": name})
    rows.sort(key=lambda r: (r["room"], r["name"]))
    return rows


def build():
    rows = zone_rows()
    body = (
        "// Generated by ops/build_photo_check_data.py. Do not hand edit.\n"
        "// The 114 zone ids photo-check.js offers in its zone picker, each\n"
        "// one a slug GET /v1/zones (photos/methodology.py) also returns.\n"
        "window.PHOTO_CHECK_ZONES = " +
        json.dumps(rows, separators=(",", ":")) + ";\n"
    )
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(body)
    return OUT, len(rows)


def main() -> int:
    path, n = build()
    print("wrote %s (%d zones)" % (os.path.relpath(path, ROOT), n))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
